# Значки, заказанные отдельной константой: по ним ищет tag(), чтобы эмодзи из
# каталога игр (registry.GameSpec.emoji) в текстах выглядел так же, как в
# остальных экранах.
_EXTRA_IDS = {
    '💸': CASHIER_ID,
    '⬆️': CASHIER_ID,
    '⬇️': CASHIER_ID,
    '📈': CRASH_ID,
    '📊': STATS_ID,
    '🏆': STATS_ID,
}


def tag(fallback: str) -> str:
    """Значок по самому эмодзи. Незаказанный эмодзи возвращается как есть."""
    emoji_id = EMOJI_IDS.get(fallback) or _EXTRA_IDS.get(fallback)
    return emoji(emoji_id, fallback) if emoji_id else fallback


_TAG_RE = re.compile(r'<tg-emoji[^>]*>(.*?)</tg-emoji>', re.S)


def strip(text: str) -> str:
    """Снять теги, оставив подложки — для мест, где HTML не разбирается."""
    return _TAG_RE.sub(r'\1', text or '')
