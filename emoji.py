"""Премиальные значки (Telegram Custom Emoji) — готовыми константами.

Раньше значки подставлял слой на сессии бота: он перехватывал каждый исходящий
запрос и менял обычные эмодзи на теги. Теперь теги лежат прямо в текстах —
работают с первой же отправки, ничего не переписывается на ходу.

Тег <tg-emoji emoji-id="…">🎲</tg-emoji> Telegram разбирает **только** в тексте
и подписи сообщения. Отсюда правила:

* тексты сообщений — константы из этого модуля;
* подписи кнопок (keyboards.py, kb.btn в играх) и тосты call.answer() —
  обычный юникод, иначе игрок увидит саму разметку;
* знак доллара остаётся обычным «$»: db.fmt подписывает и тексты, и кнопки,
  и тосты, а один формат суммы на всё лучше трёх.

Внутри тега стоит ровно один обычный эмодзи — он же подложка для тех, у кого
значок не отрисовался. ASCII-подложку (например «$») Telegram не принимает
вообще, поэтому в таблице только эмодзи.

Значки — платная возможность: их принимают только от ботов с юзернеймом,
купленным на Fragment. Если Telegram начнёт отвечать CUSTOM_EMOJI_INVALID,
достаточно запустить бота с PREMIUM_EMOJI=0 — все константы станут обычными
эмодзи, и тексты этого даже не заметят.
"""

