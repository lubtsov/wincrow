def _animation(*names: str) -> Path | None:
    """Первый существующий файл из списка имён. Ничего не нашлось — None.

    Кандидатов несколько потому, что гифку кладут в проект как попало: Telegram
    отдаёт её уже перекодированной в mp4 (`video_623185.gif.mp4`), браузер
    сохраняет как `.gif`, а прежняя версия держала её в подпапке `videy/`.
    Файл ищется по всем этим вариантам, и переименовывать ничего не нужно.
    """
    for name in names:
        path = ROOT_DIR / name
        if path.is_file():
            return path
    return None


