def support_url() -> str | None:
    """Ссылка на поддержку для url-кнопки. None — если в конфиге не юзернейм.

    В SUPPORT_NAME может лежать что угодно (телефон, «пиши в чат»), поэтому
    ссылка собирается только из того, что действительно похоже на @username:
    5–32 символа из букв, цифр и подчёркиваний. Иначе Telegram отклонит всю
    клавиатуру целиком из-за одной битой кнопки.
    """
    name = SUPPORT_NAME.strip().lstrip('@')
    if 5 <= len(name) <= 32 and all(c.isascii() and (c.isalnum() or c == '_')
                                    for c in name):
        return f'https://t.me/{name}'
    return None

