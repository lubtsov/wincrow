"""Каталог игр.

Файл — только метаданные: ключ, название, группа, правила. Никаких импортов
из handlers/keyboards, иначе получим тот же цикл, что был в прежней версии
между main / games / payment.

Модуль конкретной игры сам заявляет о себе через @implement(key). Пока игра
не написана, spec.ready == False, и меню показывает её как «скоро».
Так каталог всегда честно отражает то, что реально работает.
"""

from dataclasses import dataclass
from typing import Callable

import emoji as E


@dataclass
class GameSpec:
    key: str
    title: str
    emoji: str
    group: str
    short: str                    # одна строка для списка игр
    rules: str                    # экран правил
    ready: bool = False           # выставляется @implement
    start: Callable | None = None  # запуск раунда, ставится @implement
    # Игры со своим экраном входа (PvP-комнаты) не показывают общий экран ставки.
    own_entry: bool = False

    @property
    def tag(self) -> str:
        """Значок для текста сообщения. В подписи кнопки нужен spec.emoji."""
        return E.tag(self.emoji)


@dataclass
class Group:
    key: str
    title: str
    emoji: str
    note: str

    @property
    def tag(self) -> str:
        return E.tag(self.emoji)


