# --- регистрация реализаций -------------------------------------------------

def implement(key: str):
    """Помечает игру как рабочую и вешает её обработчик запуска раунда."""
    def deco(fn):
        spec = GAMES[key]
        spec.start = fn
        spec.ready = True
        return fn
    return deco


def by_group(group: str) -> list[GameSpec]:
    return [g for g in GAMES.values() if g.group == group]


def ready_games() -> list[GameSpec]:
    return [g for g in GAMES.values() if g.ready]
